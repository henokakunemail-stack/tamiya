----------以txt方式加载配置表---start
local configName = 'dictmail.txt'
function dictmail_config.Load()
	 local content = loadConfig(configName)
	 local lines = stringSplit(content, '\n')
	 local len = #lines
	 local index = 4
	 while index <= len - 1 do
		 local line = lines[index]
		 local columns = stringSplit(line, '\t')
		 local row = {
		 C_ID = ConvertToNumber(configName, 'C_ID', columns[1]),
		 icon = columns[2],
		 title = columns[3],
		 content = columns[4],
		 sender = columns[5],
		 }
		 table.insert(configData,row)
		 configIdx[row.C_ID]=#configData
		 index = index + 1
		 line = nil
		 columns = nil
	 end
	 lines = nil
end
dictmail_config.Load()
----------以pb方式加载配置表---end




---@return table<number,dictmail_config_cell>
function dictmail_config.GetConfigData() return configData end
---@return dictmail_config_cell
function dictmail_config.GetById(id)
	 if id == nil or configIdx[id]== nil or configData[configIdx[id]] == nil then
		 return nil
	 end
	 return configData[configIdx[id]]
end








