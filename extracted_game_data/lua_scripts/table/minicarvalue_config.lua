----------以txt方式加载配置表---start
local configName = 'minicarvalue.txt'
function minicarvalue_config.Load()
	 local content = loadConfig(configName)
	 local lines = stringSplit(content, '\n')
	 local len = #lines
	 local index = 4
	 while index <= len - 1 do
		 local line = lines[index]
		 local columns = stringSplit(line, '\t')
		 local row = {
		 C_ID = ConvertToNumber(configName, 'C_ID', columns[1]),
		 value = ConvertToNumber(configName, 'value', columns[2]),
		 desc = columns[3],
		 }
		 table.insert(configData,row)
		 configIdx[row.C_ID]=#configData
		 index = index + 1
		 line = nil
		 columns = nil
	 end
	 lines = nil
end
minicarvalue_config.Load()
----------以pb方式加载配置表---end




---@return table<number,minicarvalue_config_cell>
function minicarvalue_config.GetConfigData() return configData end
---@return minicarvalue_config_cell
function minicarvalue_config.GetById(id)
	 if id == nil or configIdx[id]== nil or configData[configIdx[id]] == nil then
		 return nil
	 end
	 return configData[configIdx[id]]
end








